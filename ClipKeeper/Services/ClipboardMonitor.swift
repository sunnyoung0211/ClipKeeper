import AppKit
import CryptoKit

/// 监听系统剪贴板的变化，发现新内容就交给 ClipboardStore 保存。
///
/// macOS 没有提供"剪贴板变化"的通知，所以只能定时检查。
/// 剪贴板有一个 `changeCount` 计数器，每次有人复制东西它就会加 1，
/// 我们只需要每隔 0.5 秒看一眼这个数字有没有变化即可，开销非常小。
final class ClipboardMonitor {
    private let pasteboard = NSPasteboard.general
    private let store: ClipboardStore
    private let settings: AppSettings
    private var lastChangeCount: Int
    private var timer: Timer?

    /// 密码管理器等应用会在复制敏感内容时附带这些"标记类型"，
    /// 遇到它们就不记录。约定来自 http://nspasteboard.org
    private let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
    ]

    /// 太大的内容不保存，避免数据库膨胀
    private let maxTextLength = 1_000_000          // 约 100 万个字符
    private let maxImageBytes = 20 * 1024 * 1024   // 20 MB

    init(store: ClipboardStore, settings: AppSettings) {
        self.store = store
        self.settings = settings
        self.lastChangeCount = pasteboard.changeCount
    }

    func start() {
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            // Timer 的回调在主线程执行，这里告诉编译器"放心，现在就在主线程"
            MainActor.assumeIsolated {
                self?.checkForChanges()
            }
        }
        // 加到 .common 模式，这样菜单展开时计时器也不会暂停
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    /// 我们自己往剪贴板写入内容后调用，避免把它当成新内容再记录一遍
    func ignoreCurrentChange() {
        lastChangeCount = pasteboard.changeCount
    }

    // MARK: - 检查与读取

    private func checkForChanges() {
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        if settings.isPaused { return }

        // 1. 跳过密码等敏感内容
        let types = Set(pasteboard.types ?? [])
        if !types.isDisjoint(with: ignoredTypes) { return }

        // 2. 跳过用户设置里忽略的应用
        let frontApp = NSWorkspace.shared.frontmostApplication
        if let bundleID = frontApp?.bundleIdentifier, settings.ignoredBundleIDs.contains(bundleID) {
            return
        }

        // 3. 读取内容并保存
        guard let item = readCurrentItem() else { return }
        item.sourceAppName = frontApp?.localizedName
        item.sourceBundleID = frontApp?.bundleIdentifier
        store.add(item)
    }

    /// 读取剪贴板的当前内容。
    /// 读取顺序很重要：在 Finder 里复制文件时，剪贴板里同时有"文件"和"文件名文本"；
    /// 在 Word 里复制文字时，同时有"文本"和"图片"。所以按 文件 → 文本 → 图片 的顺序判断。
    private func readCurrentItem() -> ClipItem? {
        // 文件
        let fileOptions: [NSPasteboard.ReadingOptionKey: Any] = [.urlReadingFileURLsOnly: true]
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: fileOptions) as? [URL],
           !urls.isEmpty {
            let paths = urls.map(\.path)
            let names = urls.map(\.lastPathComponent).joined(separator: "\n")
            return ClipItem(
                kind: .file,
                text: names,
                filePaths: paths,
                contentHash: Self.hash("file:" + paths.joined(separator: "\n"))
            )
        }

        // 文本
        if let text = pasteboard.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
           text.count <= maxTextLength {
            return ClipItem(kind: .text, text: text, contentHash: Self.hash("text:" + text))
        }

        // 图片（统一转成 PNG 保存，体积比 TIFF 小很多）
        if let rawData = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff),
           let bitmap = NSBitmapImageRep(data: rawData),
           let png = bitmap.representation(using: .png, properties: [:]),
           png.count <= maxImageBytes {
            return ClipItem(
                kind: .image,
                imageData: png,
                imageWidth: bitmap.pixelsWide,
                imageHeight: bitmap.pixelsHigh,
                contentHash: Self.hash(png)
            )
        }

        return nil
    }

    // MARK: - 计算内容指纹（SHA-256）

    private static func hash(_ string: String) -> String {
        hash(Data(string.utf8))
    }

    private static func hash(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }
}
